import { OrderStatus } from '../enums/order';

/**
 * ด่านเดียวที่ตัดสินว่า "เบิกเงินได้หรือยัง" — `CR-036` · `REQ-RPT-021`
 *
 * ใช้ร่วมกันทั้ง 3 รายงานค่าตอบแทน (ไรเดอร์ · Technician · Device Manager)
 * **ห้ามเขียนเงื่อนไขนี้ซ้ำที่อื่น** — เงื่อนไขเรื่องเงินที่กระจายหลายที่คือต้นเหตุของ
 * ยอดสองชุดที่ไม่ตรงกัน (บทเรียนเดียวกับ `reportTotals` — ข้อควรระวังข้อ 220)
 */

/**
 * `REQ-RPT-021` — เบิกได้เมื่อใบงานมีสถานะ **สำเร็จ (`COMPLETED`)** เท่านั้น
 *
 * ก่อนถึง `COMPLETED` ทุกขายัง "เบิกไม่ได้" แม้ขานั้นจะทำเสร็จไปแล้วก็ตาม เพราะใบงาน
 * ที่ยังไม่ปิดยังถูกยกเลิกได้อยู่ (DOM-02 §2.4 — `CANCELLED` ออกจากทุกสถานะที่ยังไม่จบ)
 * ถ้าจ่ายไปก่อนแล้วใบงานถูกยกเลิกทีหลัง เงินนั้นเรียกคืนไม่ได้
 *
 * ⚠️ นี่เป็น **ด่านเพิ่ม ไม่ใช่ด่านแทน** — ยังต้องผ่านเงื่อนไขของขานั้นเองทุกข้อ
 *    (ผู้ทำ · เรท · ระยะ · ประวัติว่าขานั้นเสร็จแล้ว)
 *    Admin ปรับสถานะข้ามลำดับไป `COMPLETED` ได้ (`REQ-ORD-052`) ถ้าใช้ด่านนี้ด่านเดียว
 *    ใบงานที่ถูกกดข้ามจะจ่ายเงินทุกขาทันทีโดยไม่มีหลักฐานว่าใครทำ
 *
 * ⚠️ **ยืนยันโดยเจ้าของงาน 2026-10-21** (`Q-092` RESOLVED · `ADR-065`) — **ห้ามเปลี่ยนให้เป็น
 *    ด่านแทนโดยไม่เปิด CR ใหม่** · เปลี่ยนบรรทัดเดียวในฟังก์ชันนี้ = ยอดเงินของทั้ง 3 รายงาน
 *    ขยับทันที และไม่มีอะไรฟ้องนอกจาก `staff-payout-projection.spec.ts` ที่ตรึงค่าไว้
 *    (บทเรียนเดียวกับ `STAFF_PAYOUT_COMPLETION_STATUS` ของ `Q-091`)
 */
export function payoutEligibleStatus(status: OrderStatus): boolean {
  return status === OrderStatus.COMPLETED;
}
